/* Scans images/listings/<folder>/ and writes listing-photos.js:
     window.LISTING_PHOTOS = { "<folder>": ["images/listings/<folder>/primary", ...] }
   Ordering: the "<folder>.<ext>" base file first (primary), then "<folder>-N.<ext>"
   in numeric order, then anything else alphabetically. Re-run whenever photos change:
     node gen-listing-photos.js */
const fs = require("fs"), path = require("path");
const ROOT = path.join(__dirname, "images", "listings");
const IMG = /\.(jpe?g|png|webp|avif)$/i;

const out = {};
for (const folder of fs.readdirSync(ROOT)) {
  const dir = path.join(ROOT, folder);
  if (!fs.statSync(dir).isDirectory()) continue;
  const files = fs.readdirSync(dir).filter(f => IMG.test(f));
  const rank = f => {
    const stem = f.replace(IMG, "");
    if (stem === folder) return [0, 0, f];                 // base = primary/cover
    const m = stem.match(/(\d+)(?!.*\d)/);                 // the LAST number in the name (e.g. -seldovia-ak-10)
    if (m) return [1, parseInt(m[1], 10), f];              // order by that number
    return [2, 0, f];                                       // anything else
  };
  files.sort((a, b) => { const ra = rank(a), rb = rank(b); return ra[0]-rb[0] || ra[1]-rb[1] || ra[2].localeCompare(rb[2]); });
  if (files.length) out[folder] = files.map(f => `images/listings/${folder}/${f}`);
}

const js = "/* AUTO-GENERATED by gen-listing-photos.js — do not edit by hand. */\nwindow.LISTING_PHOTOS = " + JSON.stringify(out, null, 0) + ";\n";
fs.writeFileSync(path.join(__dirname, "listing-photos.js"), js);
console.log("folders with photos:", Object.keys(out).length);
for (const k of Object.keys(out)) console.log(`  ${k}: ${out[k].length} photo(s)`);
